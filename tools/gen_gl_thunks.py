#!/usr/bin/env python3
"""Generate Win64 -> host thunks for every OpenGL command in the Khronos gl.xml.

usage: gen_gl_thunks.py gl.xml manual.txt out.c

Each thunk reads its arguments with the Win64 convention and calls the host
entry point, resolved lazily through gl_host_proc(). Names listed in manual.txt
are left to runtime/src/gl_bridge.c (callbacks, GLES translation).
"""
import re, sys
import xml.etree.ElementTree as ET

xml, manual_path, out = sys.argv[1], sys.argv[2], sys.argv[3]
manual = set()
for l in open(manual_path):
    l = l.split('#')[0].strip()
    if l: manual.add(l)

INT32 = {'GLenum', 'GLuint', 'GLint', 'GLsizei', 'GLbitfield', 'GLfixed', 'GLhandleARB', 'GLclampx'}
SMALL = {'GLboolean': 'uint8_t', 'GLbyte': 'int8_t', 'GLubyte': 'uint8_t', 'GLshort': 'int16_t',
         'GLushort': 'uint16_t', 'GLchar': 'int8_t', 'GLcharARB': 'int8_t', 'GLhalf': 'uint16_t',
         'GLhalfNV': 'uint16_t', 'GLhalfARB': 'uint16_t'}
INT64 = {'GLint64', 'GLuint64', 'GLint64EXT', 'GLuint64EXT', 'GLintptr', 'GLsizeiptr', 'GLintptrARB',
         'GLsizeiptrARB', 'GLsync', 'GLeglImageOES', 'GLeglClientBufferEXT', 'GLvdpauSurfaceNV'}
FLT = {'GLfloat', 'GLclampf'}
DBL = {'GLdouble', 'GLclampd'}
CALLBACK = {'GLDEBUGPROC', 'GLDEBUGPROCARB', 'GLDEBUGPROCKHR', 'GLDEBUGPROCAMD', 'GLVULKANPROCNV'}

def ctype(text):
    """-> (kind, c type) kind in i32 small i64 ptr f d void, or None"""
    t = re.sub(r'\bconst\b', '', text).strip()
    t = re.sub(r'\s+', ' ', t)
    if '*' in t:
        return 'ptr', 'void *'
    if t == 'void':
        return 'void', 'void'
    if t in INT32:
        return ('i32', 'uint32_t') if t in ('GLenum', 'GLuint', 'GLbitfield', 'GLhandleARB') else ('i32', 'int32_t')
    if t in SMALL:
        return 'small', SMALL[t]
    if t in INT64:
        return 'i64', 'uint64_t' if t in ('GLuint64', 'GLuint64EXT') else 'int64_t' if t not in ('GLsync', 'GLeglImageOES', 'GLeglClientBufferEXT') else 'void *'
    if t in FLT:
        return 'f', 'float'
    if t in DBL:
        return 'd', 'double'
    return None, t

root = ET.parse(xml).getroot()
cmds = []
for cmd in root.find('commands').findall('command'):
    proto = cmd.find('proto')
    name = proto.find('name').text
    rtext = (proto.text or '') + ''.join((e.text or '') + (e.tail or '') for e in proto if e.tag != 'name')
    rtext = rtext.strip()
    params = []
    ok = True
    for p in cmd.findall('param'):
        full = (p.text or '') + ''.join(((e.text or '') if e.tag != 'name' else '') + (e.tail or '') for e in p)
        pt = p.find('ptype')
        if pt is not None and pt.text in CALLBACK:
            ok = False
        params.append(full.strip())
    cmds.append((name, rtext, params, ok))

o = ['/* generated by tools/gen_gl_thunks.py from gl.xml - do not edit */',
     '#include "w64.h"', '#include "sdl_bridge.h"', '',
     'void *gl_host_proc(const char *name);',
     '#define GLT(n) do { if (w64_trace >= 3) w64_log("[gl] %s", n); } while (0)',
     'extern int w64_glcheck; void gl_check(const char *n);',
     'static void gl_missing(CPU *c, const char *n) { w64_fatal(c, "host has no GL entry point %s", n); }', '']
table = []
seen = set()
for name, rtext, params, ok in sorted(cmds):
    if name in seen or name in manual:
        continue
    seen.add(name)
    rk, rt = ctype(rtext)
    kinds = [ctype(p) for p in params]
    if not ok or rk is None or any(k is None for k, _ in kinds):
        continue
    proto = ', '.join(t for _, t in kinds) or 'void'
    args = []
    for i, (k, t) in enumerate(kinds):
        if k == 'f':
            args.append('AF(%d)' % i)
        elif k == 'd':
            args.append('AD(%d)' % i)
        elif k == 'ptr':
            args.append('AP(%d)' % i)
        elif k == 'small':
            args.append('(%s)A(%d)' % (t, i))
        else:
            args.append('(%s)A(%d)' % (t, i))
    call = 'p(%s)' % ', '.join(args)
    chk = '' if name == 'glGetError' else ' if (w64_glcheck) gl_check("%s");' % name
    if rk == 'void':
        tail = '%s;%s RETV();' % (call, chk)
    elif rk == 'f':
        tail = 'float r = %s;%s RETF(r);' % (call, chk)
    elif rk == 'd':
        tail = 'double r = %s;%s RETD(r);' % (call, chk)
    elif rk == 'ptr' or rt == 'void *':
        tail = 'void *r = %s;%s RET((uintptr_t)r);' % (call, chk)
    else:
        tail = '%s r = %s;%s RET((uint64_t)r);' % (rt, call, chk)
    o.append('static %s (*p_%s)(%s);' % (rt, name, proto))
    o.append('static void t_%s(CPU *c) { GLT("%s"); %s (*p)(%s) = p_%s; if (!p) { p = p_%s = (%s (*)(%s))gl_host_proc("%s"); if (!p) gl_missing(c, "%s"); } %s }'
             % (name, name, rt, proto, name, name, rt, proto, name, name, tail))
    table.append(name)

o.append('')
o.append('typedef struct { const char *name; w64_fn fn; } gl_thunk_t;')
o.append('const gl_thunk_t gl_thunks[] = {')
for n in table:
    o.append('    { "%s", t_%s },' % (n, n))
o.append('};')
o.append('const unsigned gl_thunk_count = %d;' % len(table))
open(out, 'w').write('\n'.join(o) + '\n')
print('%d GL commands, %d thunks generated (%d manual)' % (len(cmds), len(table), len(manual)))
