#!/usr/bin/env python3
"""Generate Win64 -> host thunks for the SDL3 dynapi jump table.

usage: gen_sdl_thunks.py <SDL source dir> <out.c>

Every SDL_DYNAPI_PROC in SDL_dynapi_procs.h becomes one slot, in order. A
procedure whose parameter and return types are all plain (integers, enums,
pointers, float/double) gets an automatic thunk: arguments are read with the
Win64 convention (position decides rcx/rdx/r8/r9 or xmm0-3, then the stack) and
passed to the host SDL function. Anything else - callbacks, varargs, va_list,
by-value structs, `long` and `wchar_t` (different widths on Win64) - gets no
thunk here; runtime/src/sdl_bridge.c implements the ones the game uses and the
rest stop with their name when called.
"""
import os, re, sys

sdl = sys.argv[1]
out = sys.argv[2]
procs_h = os.path.join(sdl, 'src', 'dynapi', 'SDL_dynapi_procs.h')
inc = os.path.join(sdl, 'include', 'SDL3')

hdr = ''
for fn in sorted(os.listdir(inc)):
    if fn.endswith('.h'):
        hdr += open(os.path.join(inc, fn), encoding='utf-8', errors='replace').read() + '\n'

structs = set(re.findall(r'typedef\s+(?:struct|union)\s+(\w+)\s*\{', hdr))
structs |= set(re.findall(r'typedef\s+(?:struct|union)\s*\{[^}]*\}\s*(\w+)\s*;', hdr, re.S))
fnptrs = set(re.findall(r'typedef\s+[^;{}]*?\(\s*SDLCALL\s*\*\s*(\w+)\s*\)', hdr))
fnptrs |= set(re.findall(r'typedef\s+[^;{}]*?\(\s*\*\s*(\w+)\s*\)\s*\(', hdr))
# typedef struct X *Y;  (opaque handle pointers)
ptr_typedefs = set(re.findall(r'typedef\s+struct\s+\w+\s*\*\s*(\w+)\s*;', hdr))

MACROS = re.compile(r'\b(SDL_PRINTF_FORMAT_STRING|SDL_SCANF_FORMAT_STRING|SDL_(?:IN|OUT|INOUT)_(?:Z_)?(?:BYTE)?CAP\([^)]*\))\s*')

def split_top(s):
    parts, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            parts.append(cur); cur = ''
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return [p.strip() for p in parts]

def classify(t):
    """-> 'i' integer/pointer slot, 'f' float, 'd' double, 'v' void, or None (manual)"""
    t = MACROS.sub('', t).strip()
    t = re.sub(r'\bconst\b', '', t).strip()
    t = re.sub(r'\s+', ' ', t)
    if t == 'void':
        return 'v', t
    if '*' in t:
        base = t.replace('*', '').strip()
        if base in ('wchar_t',):
            return None, t
        return 'i', t
    if t in ('float',):
        return 'f', t
    if t in ('double',):
        return 'd', t
    if t in ('va_list', 'wchar_t', 'long', 'unsigned long', '...'):
        return None, t
    if t in fnptrs or t == 'SDL_FunctionPointer':
        return None, t
    if t in structs and t not in ptr_typedefs:
        return None, t
    return 'i', t

lines = open(procs_h).read()
procs = []
for m in re.finditer(r'^SDL_DYNAPI_PROC\((.*)\)\s*$', lines, re.M):
    body = m.group(1)
    parts = split_top(body)
    rc, fn, params = parts[0], parts[1], parts[2]
    procs.append((rc.strip(), fn.strip(), params.strip()[1:-1].strip()))

o = []
o.append('/* generated by tools/gen_sdl_thunks.py from SDL %s - do not edit */' % os.path.basename(os.path.abspath(sdl)))
o.append('#include "w64.h"')
o.append('#include <SDL3/SDL.h>')
o.append('#include "sdl_bridge.h"')
o.append('')
names = []
auto = 0
for rc, fn, params in procs:
    plist = [] if params in ('', 'void') else split_top(params)
    ok = True
    args = []
    for i, p in enumerate(plist):
        if p.strip() == '...':
            ok = False; break
        p2 = MACROS.sub('', p).strip()
        mm = re.match(r'(.*?)(\w+)\s*$', p2)
        if not mm:
            ok = False; break
        ty = mm.group(1).strip()
        k, tn = classify(ty)
        if k is None:
            ok = False; break
        if k == 'i' and tn == 'bool':
            args.append('(bool)(uint8_t)A(%d)' % i)      # Win64 sets only the low byte
        elif k == 'i':
            args.append('(%s)(uintptr_t)A(%d)' % (ty, i) if '*' in ty else '(%s)A(%d)' % (ty, i))
        elif k == 'f':
            args.append('AF(%d)' % i)
        elif k == 'd':
            args.append('AD(%d)' % i)
    rk, rtn = classify(rc)
    if rk is None:
        ok = False
    # declared only on some platforms (or outside SDL.h): never a guest concern
    if re.search(r'GDK|Android|DXGI|Direct3D9|iOS|iPhone|IsChromebook|IsDeXMode|OnApplication|RegisterApp|UnregisterApp|'
                 r'SetMainReady|Vulkan_|WindowsMessageHook|X11EventHook|LinuxThreadPriority|UIKit', fn):
        ok = False
    if not ok:
        names.append((fn, None))
        continue
    call = '%s(%s)' % (fn, ', '.join(args))
    if rk == 'v':
        b = '%s; RETV();' % call
    elif rk == 'f':
        b = 'float r = %s; RETF(r);' % call
    elif rk == 'd':
        b = 'double r = %s; RETD(r);' % call
    elif '*' in rc:
        b = '%s r = %s; RET((uintptr_t)r);' % (rc, call)
    else:
        b = '%s r = %s; RET((uint64_t)r);' % (rc, call)
    tr = 'SDLT_TRACE("%s"); ' % fn
    o.append('static void t_%s(CPU *c) { %s%s }' % (fn, tr, b))
    names.append((fn, 't_' + fn))
    auto += 1

o.append('')
o.append('const sdl_proc_t sdl_procs[] = {')
for fn, t in names:
    o.append('    { "%s", %s },' % (fn, t or 'NULL'))
o.append('};')
o.append('const unsigned sdl_proc_count = %d;' % len(names))
open(out, 'w').write('\n'.join(o) + '\n')
print('%d procedures, %d automatic thunks, %d need manual code' % (len(names), auto, len(names) - auto))
